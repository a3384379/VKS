/* Reproducible single-file reader assets; no network is needed by the reader. */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import { build, transform } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "services/api/vks_api/reader_assets");
const options = {
  bundle: true,
  minify: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  write: false,
  metafile: true,
  legalComments: "eof",
};
const diagrams = await build({
  ...options,
  entryPoints: [path.join(root, "scripts/reader_diagram.mjs")],
});
const runtime = gzipSync(diagrams.outputFiles[0].contents, {
  level: 9,
}).toString("base64");
const markdown = await build({
  ...options,
  entryPoints: [path.join(root, "scripts/reader_markdown.mjs")],
  define: { __VKS_MERMAID_GZIP__: JSON.stringify(runtime) },
});
const javascript = markdown.outputFiles[0].text.replace(
  /<\/script/gi,
  "<\\/script",
);
await fs.writeFile(path.join(output, "markdown-vendor.js"), javascript + "\n");

let css = await fs.readFile(
  path.join(root, "node_modules/katex/dist/katex.min.css"),
  "utf8",
);
// Modern browser support is already required for DecompressionStream. Embed one
// WOFF2 source per font instead of carrying duplicate WOFF/TTF font copies.
css = css.replace(/src:([^;}]+)(;|})/g, (all, sources, end) => {
  const preferred = sources.match(/url\(([^)]+\.woff2)\)\s*format\("woff2"\)/);
  return preferred ? `src:${preferred[0]}${end}` : all;
});
const fonts = [...css.matchAll(/url\((fonts\/[^)]+)\)/g)];
for (const match of fonts) {
  const raw = await fs.readFile(
    path.join(root, "node_modules/katex/dist", match[1]),
  );
  css = css.replaceAll(
    `url(${match[1]})`,
    `url(data:font/woff2;base64,${raw.toString("base64")})`,
  );
}
css += await fs.readFile(
  path.join(root, "scripts/reader_markdown.css"),
  "utf8",
);
css = (await transform(css, { loader: "css", minify: true })).code.replace(
  /<\/style/gi,
  "<\\/style",
);
await fs.writeFile(path.join(output, "markdown-vendor.css"), css);

const packages = new Set();
for (const file of [
  ...Object.keys(diagrams.metafile.inputs),
  ...Object.keys(markdown.metafile.inputs),
]) {
  const name = file.split("node_modules/")[1]?.split("/");
  if (name)
    packages.add(
      name[0].startsWith("@") ? name.slice(0, 2).join("/") : name[0],
    );
}
packages.add("katex");
const notices = [
  "VKS reader third-party licenses (generated by npm run build:reader)",
];
for (const name of [...packages].sort()) {
  const folder = path.join(root, "node_modules", name);
  const meta = JSON.parse(
    await fs.readFile(path.join(folder, "package.json"), "utf8"),
  );
  notices.push(
    `\n${name}@${meta.version} — ${meta.license || "see upstream license"}`,
  );
  for (const file of (await fs.readdir(folder)).filter((name) =>
    /^(license|licence|copying)(\.|$)/i.test(name),
  ))
    notices.push(await fs.readFile(path.join(folder, file), "utf8"));
}
await fs.writeFile(
  path.join(output, "markdown-licenses.txt"),
  notices.join("\n") + "\n",
);
console.log(
  `Reader Markdown: ${javascript.length} JS bytes, ${css.length} CSS bytes; Mermaid stays compressed until needed.`,
);
